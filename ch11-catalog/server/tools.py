"""The three governed-data tools as plain functions.

server.py registers them with the MCP SDK; cli.py calls them directly, so you can
watch every behavior without an agent. The docstrings are the tool descriptions
the agent routes on.
"""
import hashlib
import hmac
import os
import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "warehouse"))
import dataplatform  # noqa: E402
from validate import Catalog, compile_to_sql, current_identity, format_rejection  # noqa: E402

# Signs generated SQL so the executor can tell it came from the generator.
# A per-process key means SQL generated by one server process can't be replayed
# into another; set CATALOG_SIGNING_KEY to share a key across processes.
KEY = os.environ.get("CATALOG_SIGNING_KEY", "").encode() or secrets.token_bytes(32)
TRAILER = re.compile(r"\n-- governed: catalog (\S+), identity (\S+), signature ([0-9a-f]{16})\s*$")


def scopes():
    return set(os.environ.get("CATALOG_SCOPES", "catalog:read").split())


def _sign(sql, revision, identity):
    msg = f"{sql}\n{revision}\n{identity}".encode()
    return hmac.new(KEY, msg, hashlib.sha256).hexdigest()[:16]


def render_catalog(metrics):
    out = []
    for m in metrics:
        out.append(f"{m['name']} ({m['label']})\n"
                   f"  definition: {m['description']}\n"
                   f"  computed as: {m['expression']}\n"
                   f"  rows counted: {' and '.join(m['bindings']['filters']) or 'all'}\n"
                   f"  grain: {m['grain']}; time ranges are whole months, e.g. 2026-Q3, 2026, 2026-03, 2026-01..2026-06\n"
                   f"  valid dimensions: {', '.join(m['dimensions'])}\n"
                   f"  owner: {m['owner']}")
    return "\n\n".join(out)


def navigate_catalog(concept: str = "", entity: str = "") -> str:
    """Find the governed metrics that match a business concept, with each metric's
    definition, grain, and valid dimensions. Use this first for any question that
    asks for a number, a trend, or a breakdown from company data, to confirm which
    metric answers it and which dimensions it can be sliced by. Returns metadata
    only, never data. An empty concept lists every metric you may query."""
    if "catalog:read" not in scopes():
        return "Forbidden: navigate_catalog needs the catalog:read scope."
    catalog = Catalog()
    matches = catalog.search(concept=concept, entity=entity)
    if not matches:
        return (f"No metric matches {concept or entity!r}.\n"
                f"The catalog does not model: {', '.join(catalog.not_modelled)}.\n"
                f"Metrics you can query: {', '.join(sorted(catalog.metrics))}.")
    return render_catalog(matches)


def generate_governed_sql(metric: str, dimensions: list[str], time_range: str,
                          filters: dict[str, str] | None = None) -> str:
    """Generate validated SQL for one catalog metric, sliced by named dimensions
    over a time range of whole months (2026-Q3, 2026, 2026-03, 2026-01..2026-06).
    filters maps a dimension to one value, e.g. {"region": "EMEA"}. Use after
    navigate_catalog confirms the metric and dimensions exist. Returns SQL and its
    validation stamp, never results; a rejection names what failed and the valid
    alternatives."""
    if "catalog:read" not in scopes():
        return "Forbidden: generate_governed_sql needs the catalog:read scope."
    catalog = Catalog()
    plan = catalog.resolve(metric, dimensions, time_range, filters)
    if plan.errors:
        return format_rejection(plan.errors)
    sql = compile_to_sql(plan)
    identity = current_identity()
    return (f"{sql}\n-- governed: catalog {catalog.revision}, identity {identity}, "
            f"signature {_sign(sql, catalog.revision, identity)}")


def execute_query(sql: str, max_rows: int = 1000) -> str:
    """Run SQL exactly as generate_governed_sql returned it, including its last
    line, and return the rows. Applies the caller's data access policies, a row
    cap, and a 30-second limit. Rejects SQL that was written or edited by hand,
    or that was generated against an older catalog revision."""
    if "data:read" not in scopes():
        return "Forbidden: execute_query needs the data:read scope."
    m = TRAILER.search(sql)
    identity = current_identity()
    signed = m and m[2] == identity and hmac.compare_digest(
        m[3], _sign(sql[:m.start()], m[1], identity))
    if not signed:
        return ("Rejected: this SQL did not come from generate_governed_sql, or it was edited "
                "after generation. Call generate_governed_sql and pass its output unchanged.")
    catalog = Catalog()
    if m[1] != catalog.revision:
        return (f"Rejected: the catalog changed from revision {m[1]} to {catalog.revision} since "
                f"this SQL was generated. Generate it again.")
    body = sql[:m.start()]
    check = catalog.validate(body)
    if not check.ok:
        return "Rejected on re-validation:\n" + "\n".join(check.problems)
    try:
        cols, rows, truncated = dataplatform.run(body, identity=identity,
                                                 max_rows=min(max_rows, 5000), timeout_s=30)
    except Exception as e:
        return f"Execution failed: {e}"
    return format_rows(cols, rows, truncated)


def format_rows(cols, rows, truncated):
    lines = [" | ".join(cols)] + [" | ".join("" if v is None else str(v) for v in r) for r in rows]
    lines.append(f"({len(rows)} row{'s' if len(rows) != 1 else ''}"
                 + (", truncated at the row cap)" if truncated else ")"))
    return "\n".join(lines)
